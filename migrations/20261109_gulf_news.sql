-- GulfJobsIndia persistent Gulf aviation and visa news table.
-- Run once in the existing Supabase project's SQL Editor.
-- Additive only: existing jobs, agents, applications and storage are untouched.
CREATE TABLE IF NOT EXISTS public.gulf_news (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  url TEXT NOT NULL UNIQUE,
  source TEXT NOT NULL DEFAULT 'Google News',
  category TEXT NOT NULL CHECK (category IN ('flight', 'visa')),
  published_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS gulf_news_published_at_idx
  ON public.gulf_news (published_at DESC);

ALTER TABLE public.gulf_news ENABLE ROW LEVEL SECURITY;

